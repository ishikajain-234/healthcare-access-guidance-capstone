/**
 * Inpatient Admission State Machine Constants & Transition Validation (Architecture Freeze v2.1)
 *
 * Forward Lifecycle:
 * ADMISSION_REQUESTED -> PENDING_REVIEW -> BED_ASSIGNED -> ADMISSION_CONFIRMED -> ADMITTED -> DISCHARGED
 *
 * Operational Cancellation:
 * ADMISSION_REQUESTED -> CANCELLED
 * PENDING_REVIEW -> CANCELLED
 * BED_ASSIGNED -> CANCELLED (Releases allocated bed back to AVAILABLE)
 * ADMISSION_CONFIRMED -> CANCELLED (Releases allocated bed back to AVAILABLE)
 */

const ADMISSION_STATES = {
  ADMISSION_REQUESTED: 'ADMISSION_REQUESTED',
  PENDING_REVIEW: 'PENDING_REVIEW',
  BED_ASSIGNED: 'BED_ASSIGNED',
  ADMISSION_CONFIRMED: 'ADMISSION_CONFIRMED',
  ADMITTED: 'ADMITTED',
  DISCHARGED: 'DISCHARGED',
  CANCELLED: 'CANCELLED',
};

const ADMISSION_ALLOWED_TRANSITIONS = {
  [ADMISSION_STATES.ADMISSION_REQUESTED]: [
    ADMISSION_STATES.PENDING_REVIEW,
    ADMISSION_STATES.CANCELLED,
  ],
  [ADMISSION_STATES.PENDING_REVIEW]: [
    ADMISSION_STATES.BED_ASSIGNED,
    ADMISSION_STATES.CANCELLED,
  ],
  [ADMISSION_STATES.BED_ASSIGNED]: [
    ADMISSION_STATES.ADMISSION_CONFIRMED,
    ADMISSION_STATES.CANCELLED,
  ],
  [ADMISSION_STATES.ADMISSION_CONFIRMED]: [
    ADMISSION_STATES.ADMITTED,
    ADMISSION_STATES.CANCELLED,
  ],
  [ADMISSION_STATES.ADMITTED]: [
    ADMISSION_STATES.DISCHARGED,
  ],
  [ADMISSION_STATES.DISCHARGED]: [],
  [ADMISSION_STATES.CANCELLED]: [],
};

function isValidAdmissionTransition(fromState, toState) {
  if (!ADMISSION_ALLOWED_TRANSITIONS[fromState]) return false;
  return ADMISSION_ALLOWED_TRANSITIONS[fromState].includes(toState);
}

module.exports = {
  ADMISSION_STATES,
  ADMISSION_ALLOWED_TRANSITIONS,
  isValidAdmissionTransition,
};
