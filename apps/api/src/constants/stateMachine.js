const STATES = {
  GUIDANCE_STARTED: 'GUIDANCE_STARTED',
  SERVICE_SEARCHED: 'SERVICE_SEARCHED',
  PUBLIC_REFERENCE_FOUND: 'PUBLIC_REFERENCE_FOUND',
  PUBLIC_REFERENCE_NOT_FOUND: 'PUBLIC_REFERENCE_NOT_FOUND',
  OFFICIAL_VERIFICATION_ROUTE_SHOWN: 'OFFICIAL_VERIFICATION_ROUTE_SHOWN',
  SUPPORT_ROUTE_SHOWN: 'SUPPORT_ROUTE_SHOWN',
  GUIDANCE_COMPLETED: 'GUIDANCE_COMPLETED',
};

const ALLOWED_TRANSITIONS = {
  [STATES.GUIDANCE_STARTED]: [STATES.SERVICE_SEARCHED],
  [STATES.SERVICE_SEARCHED]: [
    STATES.PUBLIC_REFERENCE_FOUND,
    STATES.PUBLIC_REFERENCE_NOT_FOUND,
  ],
  [STATES.PUBLIC_REFERENCE_FOUND]: [STATES.OFFICIAL_VERIFICATION_ROUTE_SHOWN],
  [STATES.PUBLIC_REFERENCE_NOT_FOUND]: [STATES.SUPPORT_ROUTE_SHOWN],
  [STATES.OFFICIAL_VERIFICATION_ROUTE_SHOWN]: [STATES.GUIDANCE_COMPLETED],
  [STATES.SUPPORT_ROUTE_SHOWN]: [STATES.GUIDANCE_COMPLETED],
  [STATES.GUIDANCE_COMPLETED]: [],
};

const EVENT_TYPES = {
  SESSION_INITIALIZED: 'SESSION_INITIALIZED',
  SERVICE_CATEGORY_SELECTED: 'SERVICE_CATEGORY_SELECTED',
  SERVICE_MATCH_FOUND: 'SERVICE_MATCH_FOUND',
  SERVICE_MATCH_NOT_FOUND: 'SERVICE_MATCH_NOT_FOUND',
  OFFICIAL_ROUTE_VIEWED: 'OFFICIAL_ROUTE_VIEWED',
  SUPPORT_ROUTE_VIEWED: 'SUPPORT_ROUTE_VIEWED',
  GUIDANCE_ACKNOWLEDGED_AND_COMPLETED: 'GUIDANCE_ACKNOWLEDGED_AND_COMPLETED',
};

function isValidTransition(fromState, toState) {
  if (!ALLOWED_TRANSITIONS[fromState]) return false;
  return ALLOWED_TRANSITIONS[fromState].includes(toState);
}

module.exports = {
  STATES,
  ALLOWED_TRANSITIONS,
  EVENT_TYPES,
  isValidTransition,
};
